"""Application interfaces for knowledge organization persistence."""

from typing import Protocol


class KnowledgeRepository(Protocol):
    def create_chapter(self, owner: str, values: dict) -> dict: ...
    def get_chapter(self, owner: str, chapter_id: str) -> dict: ...
    def list_chapters(
        self, owner: str, subject_id: str, archived: bool, limit: int, cursor_id: str | None = None
    ) -> list[dict]: ...
    def update_chapter(self, owner: str, chapter_id: str, values: dict, version: int) -> dict: ...
    def create_point(self, owner: str, values: dict) -> dict: ...
    def get_point(self, owner: str, point_id: str) -> dict: ...
    def get_active_point(self, owner: str, point_id: str) -> dict: ...
    def list_points(
        self, owner: str, chapter_id: str, archived: bool, limit: int, cursor_id: str | None = None
    ) -> list[dict]: ...
    def update_point(self, owner: str, point_id: str, values: dict, version: int) -> dict: ...
    def link_problem(
        self, owner: str, problem_id: str, point_ids: list[str], version: int
    ) -> dict: ...
    def subject_space(self, owner: str, subject_id: str) -> dict: ...


class KnowledgeUnitOfWork(Protocol):
    knowledge: KnowledgeRepository

    def lock_owner(self, owner_id: str) -> None: ...
    def replay(self, owner_id: str, operation: str, key: str, fingerprint: str) -> dict | None: ...
    def remember(
        self, owner_id: str, operation: str, key: str, fingerprint: str, response: dict
    ) -> None: ...
    def commit(self) -> None: ...
