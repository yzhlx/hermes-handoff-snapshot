"""Application boundary for account data sovereignty."""

from typing import Protocol


class AccountRepository(Protocol):
    def status(self, owner_id: str) -> str: ...
    def count_records(self, owner_id: str) -> dict: ...
    def export_document(self, owner_id: str) -> dict: ...
    def create_export(self, owner_id: str, data: dict): ...
    def get_export(self, owner_id: str, export_id: str): ...
    def list_exports(self, owner_id: str, limit: int): ...
    def pending_deletion(self, owner_id: str): ...
    def create_deletion(self, owner_id: str, data: dict): ...
    def cancel_deletion(self, owner_id: str, version: int): ...
    def complete_deletion(self, owner_id: str, version: int): ...
    def purge(self, owner_id: str) -> dict: ...


class AccountUnitOfWork(Protocol):
    account: AccountRepository

    def lock_owner(self, owner_id: str) -> None: ...
    def replay(self, owner_id: str, operation: str, key: str, fingerprint: str): ...
    def remember(
        self, owner_id: str, operation: str, key: str, fingerprint: str, response: dict
    ): ...
    def commit(self) -> None: ...
