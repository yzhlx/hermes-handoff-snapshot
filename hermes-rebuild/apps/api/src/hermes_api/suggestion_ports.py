"""Application boundary for source facts and durable derived suggestions."""

from typing import Protocol


class SuggestionRepository(Protocol):
    def candidates(self, owner_id: str, now): ...
    def list_suggestions(self, owner_id: str, filters: dict, limit: int, cursor: str | None): ...
    def get_suggestion(self, owner_id: str, suggestion_id: str, now): ...
    def act(self, owner_id: str, suggestion_id: str, action: str, until, version: int, now): ...


class SuggestionUnitOfWork(Protocol):
    suggestions: SuggestionRepository

    def lock_owner(self, owner_id: str) -> None: ...
    def replay(self, owner_id: str, operation: str, key: str, fingerprint: str): ...
    def remember(
        self, owner_id: str, operation: str, key: str, fingerprint: str, response: dict
    ): ...
    def commit(self) -> None: ...
