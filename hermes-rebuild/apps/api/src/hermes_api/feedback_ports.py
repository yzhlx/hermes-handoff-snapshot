"""Application ports for feedback and problem persistence."""

from typing import Protocol


class FeedbackRepository(Protocol):
    def create_reflection(self, owner_id: str, values: dict) -> dict: ...
    def get_reflection(self, owner_id: str, session_id: str) -> dict: ...
    def create_problem(self, owner_id: str, values: dict) -> dict: ...
    def get_problem(self, owner_id: str, problem_id: str) -> dict: ...
    def list_problems(
        self,
        owner_id: str,
        subject_id: str | None,
        representative: bool | None,
        limit: int,
        cursor_id: str | None = None,
        archived: bool = False,
    ) -> list[dict]: ...
    def update_problem(
        self, owner_id: str, problem_id: str, values: dict, version: int
    ) -> dict: ...
    def list_attachment_links(self, owner_id: str, problem_id: str) -> dict: ...
    def link_attachment(
        self, owner_id: str, problem_id: str, values: dict, version: int
    ) -> dict: ...
    def unlink_attachment(
        self, owner_id: str, problem_id: str, link_id: str, version: int
    ) -> dict: ...
    def create_attempt(self, owner_id: str, values: dict) -> dict: ...
    def get_attempt(self, owner_id: str, attempt_id: str) -> dict: ...
    def update_attempt(
        self, owner_id: str, attempt_id: str, values: dict, version: int
    ) -> dict: ...
    def update_reflection(
        self, owner_id: str, session_id: str, values: dict, version: int
    ) -> dict: ...


class FeedbackUnitOfWork(Protocol):
    feedback: FeedbackRepository

    def lock_owner(self, owner_id: str) -> None: ...
    def replay(self, owner_id: str, operation: str, key: str, fingerprint: str) -> dict | None: ...
    def remember(
        self, owner_id: str, operation: str, key: str, fingerprint: str, response: dict
    ) -> None: ...
    def commit(self) -> None: ...
