"""Narrow ports used by attachment application services."""

from typing import Protocol


class PrivateObjectStore(Protocol):
    def put_stream(self, key: str, chunks, max_bytes: int) -> tuple[int, str]: ...
    def open(self, key: str): ...
    def delete(self, key: str) -> None: ...
    def put_file(self, key: str, path: str) -> None: ...


class FileValidator(Protocol):
    def inspect(self, path: str, declared_mime: str) -> dict: ...
    def render_pdf_page(self, path: str, page: int, output: str) -> dict: ...
    def render_image_preview(self, path: str, output: str) -> dict: ...


class AttachmentRepository(Protocol):
    """Owner-scoped persistence and object access; policy stays in the service."""

    def initialize(self, owner: str, body: dict, key: str) -> dict: ...
    async def upload(self, owner: str, attachment_id: str, chunks, mime: str, key: str) -> dict: ...
    def complete(self, owner: str, attachment_id: str, operation_id, key: str) -> dict: ...
    def get_attachment(self, owner: str, attachment_id: str) -> dict: ...
    def upload_policy(self, owner: str, attachment_id: str) -> dict: ...
    def find_validation_job(self, owner: str, attachment_id: str) -> dict | None: ...
    def get_job(self, owner: str, job_id: str) -> dict: ...
    def create_preview_job(
        self, owner: str, attachment_id: str, operation_id, kind: str, page: int, key: str
    ) -> dict: ...
    def open_original(self, owner: str, attachment_id: str) -> tuple[object, str]: ...
    def open_preview(self, owner: str, attachment_id: str, page: int) -> object: ...
    def run_one(self) -> bool: ...
