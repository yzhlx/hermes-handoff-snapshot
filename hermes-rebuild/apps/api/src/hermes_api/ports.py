"""Application-owned interfaces for persistence and future model adapters."""

from typing import Protocol

from .domain import LearningSession


class SessionRepository(Protocol):
    def current(self, owner_id: str) -> LearningSession | None: ...
    def get(self, owner_id: str, session_id: str) -> LearningSession: ...

    def list(
        self, owner_id: str, limit: int, cursor_id: str | None = None
    ) -> list[LearningSession]: ...
    def add(self, value: LearningSession) -> LearningSession: ...
    def transition(self, value: LearningSession, action: str, version: int) -> LearningSession: ...

    def correct_segment(
        self, value: LearningSession, segment_id: str, changes: dict, version: int
    ) -> LearningSession: ...


class UnitOfWork(Protocol):
    sessions: SessionRepository

    def lock_owner(self, owner_id: str) -> None: ...
    def owns_subject(self, owner_id: str, subject_id: str) -> bool: ...
    def replay(self, owner_id: str, operation: str, key: str, fingerprint: str) -> dict | None: ...
    def remember(
        self, owner_id: str, operation: str, key: str, fingerprint: str, response: dict
    ) -> None: ...
    def commit(self) -> None: ...


class ModelPort(Protocol):
    def advise(self, evidence: list[dict], budget: int) -> dict: ...
