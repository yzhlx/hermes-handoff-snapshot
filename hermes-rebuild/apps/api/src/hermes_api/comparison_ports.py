"""Application boundary for comparisons."""

from typing import Protocol


class ComparisonRepository(Protocol):
    def create(self, owner_id: str, data: dict): ...
    def get(self, owner_id: str, comparison_id: str): ...
    def list(self, owner_id: str, filters: dict, limit: int, cursor: str | None): ...
    def patch(self, owner_id: str, comparison_id: str, data: dict, version: int): ...


class ComparisonUnitOfWork(Protocol):
    comparisons: ComparisonRepository

    def lock_owner(self, owner_id: str) -> None: ...
    def replay(self, owner_id: str, operation: str, key: str, fingerprint: str): ...
    def remember(
        self, owner_id: str, operation: str, key: str, fingerprint: str, response: dict
    ): ...
    def commit(self) -> None: ...
